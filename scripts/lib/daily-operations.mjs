const PROPERTY_TIMEZONE = "Asia/Jakarta";

export function getJakartaBusinessDate(instant = new Date(), rolloverHour = 4) {
  if (!Number.isInteger(rolloverHour) || rolloverHour < 0 || rolloverHour > 23)
    throw new Error("BUSINESS_DATE_ROLLOVER_HOUR must be an integer 0-23");
  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: PROPERTY_TIMEZONE,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    hour12: false,
  }).formatToParts(instant);
  const value = (type) => parts.find((part) => part.type === type)?.value;
  const year = value("year");
  const month = value("month");
  const day = value("day");
  const rawHour = value("hour");
  if (!year || !month || !day || rawHour === undefined)
    throw new Error("Failed to resolve Jakarta business date");
  const hour = rawHour === "24" ? 0 : Number(rawHour);
  const date = new Date(Date.UTC(Number(year), Number(month) - 1, Number(day)));
  if (hour < rolloverHour) date.setUTCDate(date.getUTCDate() - 1);
  return date.toISOString().slice(0, 10);
}

async function processProperty(client, propertyId, businessDate) {
  await client.query("BEGIN");
  try {
    await client.query(
      "SELECT pg_advisory_xact_lock(hashtextextended($1, 0))",
      [`kooka-daily-rollover:${propertyId}:${businessDate}`],
    );
    const runResult = await client.query(
      `INSERT INTO business_day_runs
        (property_id, business_date, run_type, status, started_at, idempotency_key)
       VALUES ($1, $2, 'ROLLOVER', 'RUNNING', now(), $3)
       ON CONFLICT (property_id, business_date, run_type) DO NOTHING
       RETURNING id`,
      [propertyId, businessDate, `automatic:${propertyId}:${businessDate}`],
    );
    const run = runResult.rows[0];
    if (!run) {
      await client.query("COMMIT");
      return { propertyId, businessDate, replayed: true };
    }

    const cleaning = await client.query(
      `WITH candidates AS (
        SELECT DISTINCT ON (st.id) $1::uuid property_id, ra.room_unit_id,
          st.id room_stay_id,
          CASE WHEN rr.checkout_date=$2::date THEN 'CHECKOUT' ELSE 'STAYOVER' END task_type,
          CASE WHEN rr.checkout_date=$2::date THEN 'HIGH' ELSE 'NORMAL' END priority
        FROM room_stays st
        JOIN reservation_rooms rr ON rr.id=st.reservation_room_id
        JOIN reservations r ON r.id=rr.reservation_id
        JOIN room_assignments ra ON ra.room_stay_id=st.id AND ra.status IN ('PLANNED','ACTIVE')
        WHERE r.property_id=$1 AND st.status IN ('IN_HOUSE','DUE_OUT')
          AND rr.check_in_date<=$2::date AND rr.checkout_date>=$2::date
      ) INSERT INTO cleaning_tasks
        (property_id,room_unit_id,room_stay_id,task_type,priority,status,target_at,
         requested_entry_permission,notes)
      SELECT property_id,room_unit_id,room_stay_id,task_type,priority,'REQUESTED',
        ($2::date+time '09:00') at time zone 'Asia/Jakarta',
        CASE WHEN task_type='STAYOVER' THEN 'ASK_FRONT_OFFICE' ELSE 'GRANTED' END,
        'Generated by automatic daily rollover'
      FROM candidates c WHERE NOT EXISTS (
        SELECT 1 FROM cleaning_tasks ct WHERE ct.room_stay_id=c.room_stay_id
          AND ct.task_type=c.task_type AND ct.target_at::date=$2::date
          AND ct.status<>'CANCELLED') RETURNING id`,
      [propertyId, businessDate],
    );

    await client.query(
      `WITH detected AS (
        SELECT 'INVENTORY_OVERCLAIM'::varchar check_code,
          ('inventory:'||d.id)::varchar fingerprint, 'CRITICAL'::varchar severity,
          'inventory_day'::varchar entity_type, d.id entity_id,
          jsonb_build_object('stayDate',d.stay_date,'capacity',d.physical_capacity,
            'claimed',sum(c.quantity)) details
        FROM inventory_days d
        JOIN inventory_claims c ON c.inventory_day_id=d.id AND c.claim_status='ACTIVE'
        WHERE d.property_id=$1 GROUP BY d.id HAVING sum(c.quantity)>d.physical_capacity
        UNION ALL
        SELECT 'PAYMENT_POSTING_MISSING',('payment:'||p.id),'CRITICAL','payment',p.id,
          jsonb_build_object('paymentCode',p.payment_code,'status',p.status)
        FROM payments p JOIN folios f ON f.id=p.folio_id
        JOIN reservations r ON r.id=f.reservation_id
        WHERE r.property_id=$1 AND p.status='VERIFIED' AND p.folio_entry_id IS NULL
      ) INSERT INTO reconciliation_exceptions
        (property_id,business_date,check_code,fingerprint,severity,status,entity_type,
         entity_id,details,detected_at,last_detected_at)
      SELECT $1,$2,check_code,fingerprint,severity,'OPEN',entity_type,entity_id,details,now(),now()
      FROM detected
      ON CONFLICT (property_id,fingerprint) DO UPDATE SET
        business_date=excluded.business_date, severity=excluded.severity,
        details=excluded.details, last_detected_at=now(),
        occurrence_count=reconciliation_exceptions.occurrence_count+1,
        status=CASE WHEN reconciliation_exceptions.status IN ('RESOLVED','ACCEPTED_WITH_REASON')
          THEN 'OPEN' ELSE reconciliation_exceptions.status END,
        updated_at=now(), version=reconciliation_exceptions.version+1`,
      [propertyId, businessDate],
    );

    const criticalResult = await client.query(
      `SELECT count(*)::integer count FROM reconciliation_exceptions
       WHERE property_id=$1 AND severity='CRITICAL'
         AND status IN ('OPEN','ACKNOWLEDGED','INVESTIGATING')`,
      [propertyId],
    );
    const critical = Number(criticalResult.rows[0]?.count ?? 0);
    const status = critical > 0 ? "NEEDS_ATTENTION" : "COMPLETED";
    const summary = {
      cleaningTasksCreated: cleaning.rowCount ?? cleaning.rows.length,
      unresolvedCriticalExceptions: critical,
      authoritativeDataMutated: false,
      trigger: "AUTOMATIC_WORKER",
    };
    await client.query(
      `UPDATE business_day_runs SET status=$2, finished_at=now(), summary=$3
       WHERE id=$1`,
      [run.id, status, JSON.stringify(summary)],
    );
    await client.query(
      `INSERT INTO audit_events
        (property_id,actor_type,action,target_type,target_id,after_json,result)
       VALUES ($1,'system','BUSINESS_DAY_ROLLOVER_COMPLETED','business_day_run',$2,$3,'SUCCESS')`,
      [
        propertyId,
        run.id,
        JSON.stringify({ businessDate, status, ...summary }),
      ],
    );
    await client.query("COMMIT");
    return { propertyId, businessDate, status, summary, replayed: false };
  } catch (error) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw error;
  }
}

/** Redis is only a wake-up signal; PostgreSQL lock/run rows are authoritative. */
export async function runAutomaticDailyOperations(
  pool,
  instant = new Date(),
  rolloverHour = 4,
) {
  const businessDate = getJakartaBusinessDate(instant, rolloverHour);
  const properties = await pool.query(
    "SELECT id FROM properties WHERE status='ACTIVE' ORDER BY id",
  );
  const results = [];
  for (const property of properties.rows) {
    const client = await pool.connect();
    try {
      results.push(await processProperty(client, property.id, businessDate));
    } finally {
      client.release();
    }
  }
  return results;
}
